/* ───────────────────────── helpers ───────────────────────── */

function getLang() {
  const saved = FRStore.get("fr_lang", null);
  if (saved && I18N[saved]) return saved;
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("cs")) return "cs";
  if (nav.startsWith("de")) return "de";
  if (nav === "zh-tw" || nav === "zh-hk" || nav.startsWith("zh-hant")) return "zht";
  if (nav.startsWith("zh")) return "zh";
  return "en";
}

let CURRENT_LANG = getLang();

function langInfo(code = CURRENT_LANG) {
  return LANGS.find((l) => l.code === code) || LANGS[0];
}

/** Translate a key, replacing {placeholders}. Falls back to English. */
function t(key, vars) {
  const dict = I18N[CURRENT_LANG] || I18N.en;
  let s = dict[key] != null ? dict[key] : I18N.en[key] != null ? I18N.en[key] : key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      s = s.split("{" + k + "}").join(vars[k]);
    });
  }
  return s;
}

/** Pick the current language from a {en, cs, de, zh, zht} object. */
function L(obj) {
  if (obj == null) return "";
  if (typeof obj === "string") return obj;
  return obj[CURRENT_LANG] || obj.en || "";
}

function fmtPrice(n) {
  try {
    return new Intl.NumberFormat(langInfo().locale, { style: "currency", currency: "EUR" }).format(n);
  } catch (e) {
    return "€" + n.toFixed(2);
  }
}

function fmtNum(n, digits = 1) {
  try {
    return new Intl.NumberFormat(langInfo().locale, {
      minimumFractionDigits: digits,
      maximumFractionDigits: digits,
    }).format(n);
  } catch (e) {
    return n.toFixed(digits);
  }
}

/** Apply translations to static markup: data-i18n, data-i18n-ph, data-i18n-aria, data-i18n-title */
function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nAria)));
  root.querySelectorAll("[data-i18n-title]").forEach((el) => (el.title = t(el.dataset.i18nTitle)));
  document.documentElement.lang = langInfo().html;
}

function setLang(code) {
  if (!I18N[code] || code === CURRENT_LANG) return;
  CURRENT_LANG = code;
  FRStore.set("fr_lang", code);
  applyI18n();
  document.querySelectorAll(".lang-btn").forEach((b) => {
    const on = b.dataset.lang === code;
    b.classList.toggle("active", on);
    b.setAttribute("aria-pressed", on ? "true" : "false");
  });
  document.dispatchEvent(new CustomEvent("langchange", { detail: code }));
}

/** Render the five flag buttons into a container element. */
function initLangPicker(container) {
  if (!container) return;
  container.innerHTML =
    `<span class="lang-label" data-i18n="lang_label">${t("lang_label")}</span>` +
    LANGS.map(
      (l) =>
        `<button type="button" class="lang-btn${l.code === CURRENT_LANG ? " active" : ""}" data-lang="${l.code}" aria-pressed="${
          l.code === CURRENT_LANG
        }" lang="${l.html}"><img src="${l.flag}" alt="" /><span>${l.label}</span></button>`
    ).join("");
  container.addEventListener("click", (e) => {
    const b = e.target.closest(".lang-btn");
    if (b) setLang(b.dataset.lang);
  });
}

function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}

